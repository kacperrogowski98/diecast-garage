import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';

const html=fs.readFileSync('index.html','utf8');
const scripts=[...html.matchAll(/<script(?:\s[^>]*)?>([\s\S]*?)<\/script>/g)].filter(m=>!m[0].startsWith('<script type="importmap"')).map(m=>m[1]).filter(Boolean);
assert.ok(scripts.length>=2,'Missing application scripts');
assert.ok(!html.includes("||'Ferrari'"),'Unknown brand must not be silently classified as Ferrari');
assert.ok(!html.includes("||'Nieznana marka'"),'Use the same Unassigned sentinel for missing brands throughout the app');
assert.ok(html.includes('id="dgConnectionStatus"')&&html.includes("addEventListener('offline',dgUpdateConnectionStatus)"),'Mobile connection indicator missing');
assert.ok(html.includes("if(/^https?:$/.test(location.protocol)&&navigator.onLine)"),'Offline startup must not download large catalogues');
assert.ok(html.includes('id="fPriority"')&&html.includes('id="fTargetPrice"'),'Wishlist controls missing');
assert.ok(html.includes('async function dgWriteRecoverySnapshot()')&&html.includes('async function dgRestoreRecoverySnapshot()'),'Local cloud recovery functions missing');
const pullCode=html.slice(html.indexOf('async function dgCloudPull()'),html.indexOf('dgInitClient();dgInitCatalogImport();'));
assert.ok(pullCode.indexOf('await dgWriteRecoverySnapshot();')>=0 && pullCode.indexOf('await dgWriteRecoverySnapshot();')<pullCode.indexOf('localStorage.setItem(KEY,JSON.stringify(nextState));'),'A cloud pull must persist local recovery BEFORE replacing data');
assert.ok(html.includes("groups.sort((a,b)=>Math.max(0,...b.variants.map(v=>wantedPriority"),'Wishlist priority sorting missing');
for(const [i,code] of scripts.entries())new vm.Script(code,{filename:'inline-'+i+'.js'});
const required=['id="rarityFilter"','id="photoFilter"','id="classFilter"','id="brandFilter"','id="yearFilter"','id="assortmentFilter"','id="content"','id="modalRoot"','id="catalogStatus"','dgFetchOnlineCatalog','id="showroomBtn"','openShowroom3D','open3D','dgCloudPush','dgCloudPull','exportData','importData','dgRarity'];
for(const token of required)assert.ok(html.includes(token),'Missing UI/API: '+token);
assert.ok(fs.existsSync('viewer3d.js'),'Missing interactive 3D viewer');
assert.ok(html.includes('type="importmap"'),'Missing Three.js import map');
const mapText=html.match(/<script type="importmap">([\s\S]*?)<\/script>/)?.[1];
assert.ok(mapText,'No import map JSON found');
const map=JSON.parse(mapText);
assert.ok(map.imports?.three?.startsWith('https://'),'Three.js module CDN missing');
const viewer=fs.readFileSync('viewer3d.js','utf8');
assert.ok(viewer.includes('export function openViewer('),'Missing 3D viewer entry');
assert.ok(viewer.includes('GLTFLoader'),'Missing local GLB support');
assert.ok(viewer.includes('id="dg3dDownload"') && viewer.includes('readSavedMesh(releaseId)'),'Missing GLB export for manual cross-device transfer');
assert.ok(html.includes('dgBulkCloud3D') && html.includes('data-cloud-auth') && html.includes('Pobierz brakujące modele 3D'),'Cloud bulk sync controls missing');
assert.ok(viewer.includes('model.garageCars'),'Missing collector showroom');
assert.ok(html.includes('openPack3D') && html.includes('Podgląd zestawu 3D'),'Missing multipack 3D UI');
assert.ok(viewer.includes('model.packPreview'),'Missing 3D pack display mode');
assert.ok(!viewer.includes('createCar('),'Never substitute procedurally generated cars for real Hot Wheels models');
assert.ok(viewer.includes('Model 3D tego wydania nie jest jeszcze dostępny'),'Unassigned 3D assets must have an honest missing state');
assert.ok(viewer.includes('Modele 3D nie są jeszcze dostępne dla całej kolekcji'),'Garage preview must not pretend to have exact 3D models');
const viewerSyntax=viewer.replace(/^import .*;$/gm,'').replace(/^export /gm,'');
new vm.Script(viewerSyntax,{filename:'viewer3d.js'});

const pullStart=html.indexOf('async function dgCloudPull(){');
const pullEnd=html.indexOf('</script>',pullStart);
assert.ok(pullStart>=0&&pullEnd>pullStart,'Cloud pull and backup implementation missing');
const cloudPull=html.slice(pullStart,pullEnd);
assert.ok(cloudPull.includes('exportData();')&&cloudPull.indexOf('exportData();')<cloudPull.indexOf('await dgWriteRecoverySnapshot();')&&cloudPull.indexOf('await dgWriteRecoverySnapshot();')<cloudPull.indexOf('localStorage.setItem(KEY,JSON.stringify(nextState));'),'Cloud pull must export backup and save a durable recovery snapshot before replacing local state');
const sw=fs.readFileSync('sw.js','utf8');
new vm.Script(sw,{filename:'sw.js'});
const release=html.match(/<title>Diecast Garage · (v[0-9.]+)<\/title>/)?.[1];
assert.ok(release && sw.includes('diecast-garage-shell-'+release),'Outdated PWA shell version');
const manifest=JSON.parse(fs.readFileSync('manifest.webmanifest','utf8'));
assert.equal(manifest.display,'standalone');
assert.ok(manifest.start_url);
const seed=fs.readFileSync('seed.js','utf8');
new vm.Script(seed,{filename:'seed.js'});
console.log('PASS: inline JS syntax, service worker, manifest, seed and essential UI hooks');
